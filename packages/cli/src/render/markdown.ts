import { ECOSYSTEM_LABEL } from "@iamcooked/core";
import type { Report } from "../report";

const SEV_ICON = { CRITICAL: "🔴", HIGH: "🟠", MEDIUM: "🟡", LOW: "🔵", UNKNOWN: "⚪" } as const;

function esc(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

/** GitHub-flavoured markdown — designed for PR comments and job summaries. */
export function renderMarkdown(report: Report, opts: { showDev: boolean }): string {
  const out: string[] = [];
  const a = report.analysis;
  out.push(`## iamcooked: **${report.verdict.label}** (risk ${report.riskScore}/100)`);
  out.push("");
  out.push(`> ${report.verdict.blurb}`);
  out.push("");
  const counts = [
    a.counts.MALWARE && `**${a.counts.MALWARE} malicious**`,
    a.counts.CRITICAL && `${a.counts.CRITICAL} critical`,
    a.counts.HIGH && `${a.counts.HIGH} high`,
    a.counts.MEDIUM && `${a.counts.MEDIUM} medium`,
    a.counts.LOW && `${a.counts.LOW} low`,
    a.counts.UNKNOWN && `${a.counts.UNKNOWN} unrated`,
  ].filter(Boolean);
  out.push(
    `Scanned ${report.lockfiles.filter((l) => !l.error).length} lockfile(s), ${a.dependencyCount} packages` +
      (report.mcpFiles.length ? `, ${report.mcpFiles.length} MCP config(s)` : "") +
      (counts.length ? ` — ${counts.join(", ")}.` : " — no known vulnerabilities."),
  );

  const groups = report.groups.filter((g) => opts.showDev || !g.devOnly || g.malware);
  if (groups.length) {
    out.push("");
    out.push("| | Package | Installed | Fix | Issue | Fix command |");
    out.push("|---|---|---|---|---|---|");
    for (const g of groups) {
      const top = g.findings[0]!;
      const icon = g.malware ? "☠️" : SEV_ICON[g.severity];
      const flags = [g.kev && "**KEV**", !g.direct && "transitive", g.devOnly && "dev"].filter(Boolean).join(", ");
      const issue = `[${esc(top.summary)}](${top.url})${g.findings.length > 1 ? ` +${g.findings.length - 1} more` : ""}${flags ? ` _(${flags})_` : ""}`;
      out.push(
        `| ${icon} | \`${g.packageName}\` <sub>${ECOSYSTEM_LABEL[g.ecosystem]}</sub> | ${g.installedVersion} | ${g.fixedVersion ?? (g.malware ? "remove" : "—")} | ${issue} | ${g.fixCommand ? `\`${esc(g.fixCommand)}\`` : esc(g.fixInstruction)} |`,
      );
    }
  }

  const mcp = report.mcpIssues.filter((i) => i.severity !== "INFO");
  if (mcp.length) {
    out.push("");
    out.push("### MCP config");
    out.push("");
    for (const i of mcp) out.push(`- **${i.severity}** \`${i.server}\` — ${esc(i.title)}. ${esc(i.fix)} _(${i.file})_`);
  }

  if (a.unchecked.length) {
    out.push("");
    out.push(`<details><summary>${a.unchecked.length} unpinned package(s) could not be checked</summary>\n\n${a.unchecked.map((u) => `\`${u.name}\``).join(", ")}\n\n</details>`);
  }
  out.push("");
  out.push(`<sub>Generated by [iamcooked](https://github.com/nanaagyei/iamcooked) v${report.tool.version} · data from OSV.dev and CISA KEV</sub>`);
  return out.join("\n") + "\n";
}
